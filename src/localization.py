def normalize_locale(value: str | None) -> str:
    if not value:
        return DEFAULT_LOCALE
    cleaned = value.strip()
    if cleaned in SUPPORTED_LOCALES:
        return cleaned
    return _LANGUAGE_ALIASES.get(cleaned.casefold(), DEFAULT_LOCALE)


def language_name(locale: str | None) -> str:
    return LANGUAGE_NAMES[normalize_locale(locale)]


