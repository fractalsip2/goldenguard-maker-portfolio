def greeting_for(first_name: str | None, locale: str | None) -> str:
    if not first_name:
        return ""
    normalized = normalize_locale(locale)
    return f"{first_name}，" if normalized in {"zh-Hans", "zh-Hant"} else f"{first_name}, "


def scam_label(scam_type: str, locale: str | None) -> str:
    normalized = normalize_locale(locale)
    return SCAM_LABELS[normalized].get(scam_type, SCAM_LABELS[normalized]["unknown"])


def text(locale: str | None, key: str, **values: Any) -> str:
    normalized = normalize_locale(locale)
    template = TEXT[normalized].get(key, TEXT[DEFAULT_LOCALE][key])
    return template.format(**values)


def localized_action(
    *,
    locale: str | None,
    risk_level: str,
    scam_type: str,
    is_routine: bool,
    safe_code_notice: bool,
    has_evidence: bool,
) -> str:
    normalized = normalize_locale(locale)
    actions = ACTIONS[normalized]
    if risk_level == "LOW":
        if safe_code_notice:
            return actions["low_code"]
        if is_routine or not has_evidence:
            return actions["low_routine"]
        return actions["low_caution"]
    return actions.get(scam_type, actions["unknown"])


def localized_evidence(
    *,
    locale: str | None,
    signal_flags: list[str],
    organization: str | None,
    fallback: list[str] | None = None,
    limit: int = 3,
) -> list[str]:
    normalized = normalize_locale(locale)
    if normalized == "en" and fallback:
        return fallback[:limit]

    available = EVIDENCE[normalized]
    present = set(signal_flags)
    selected: list[str] = []
    org = organization or "the organization"

    for flag in EVIDENCE_PRIORITY:
        if flag not in present or flag not in available:
            continue
        selected.append(available[flag].format(organization=org))
        if len(selected) >= limit:
            break

    if selected:
        return selected

    if normalized == "en" and fallback:
        return fallback[:limit]
    return []


def system_message(locale: str | None, key: str) -> str:
    return text(locale, key)
